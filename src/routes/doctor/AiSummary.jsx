import { useEffect, useState } from 'react'
import { Button, Card, Spinner } from '../../components/ui'
import { summarizeRecord, aiStatus } from '../../lib/ai'
import { toSummaryPayload } from '../../lib/record'

/**
 * One-tap condensation of the record. If the AI layer is missing or down this
 * degrades to a clear "unavailable" note — the record below it is unaffected.
 */
export function AiSummary({ record }) {
  const [summary, setSummary] = useState(null)
  const [busy, setBusy] = useState(false)
  const [ai, setAi] = useState({ enabled: true })

  useEffect(() => {
    aiStatus().then(setAi)
  }, [])

  async function run() {
    setBusy(true)
    const result = await summarizeRecord(toSummaryPayload(record))
    setSummary(result)
    setBusy(false)
  }

  return (
    <Card className="border-mint-500/25 bg-mint-500/[0.04]">
      <div className="flex flex-wrap items-center justify-between gap-3">
        <div>
          <h3 className="text-sm font-bold text-white">AI record summary</h3>
          <p className="text-xs text-ink-500">
            {ai.enabled === false
              ? 'No AI key configured — summaries are disabled, everything else works.'
              : 'Condenses this record into a 15-second briefing.'}
          </p>
        </div>
        <Button onClick={run} disabled={busy}>
          {busy ? <Spinner /> : summary ? 'Regenerate' : 'Summarise record'}
        </Button>
      </div>

      {summary && (
        <div className="mt-4 border-t border-ink-800 pt-3">
          {summary.ok ? (
            <ul className="space-y-1.5">
              {summary.text
                .split('\n')
                .map((line) => line.replace(/^[-•*]\s*/, '').trim())
                .filter(Boolean)
                .map((line, i) => (
                  <li key={i} className="flex gap-2 text-sm leading-relaxed text-ink-300">
                    <span className="mt-1 text-mint-400">▸</span>
                    {line}
                  </li>
                ))}
            </ul>
          ) : (
            <p className="text-sm text-amber-200">{summary.text}</p>
          )}
          {summary.provider && (
            <p className="mt-3 text-[11px] text-ink-500">
              Generated by {summary.provider}. Clinical judgement remains the doctor's.
            </p>
          )}
        </div>
      )}
    </Card>
  )
}
